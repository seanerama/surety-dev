// The CSS binding of the neutral tokens (D7 §5.1, B.11): `tokens.css`, CSS
// custom properties for `html_css` and `three_js`, generated from
// `tokens.json`; a token `color.text.primary` is `--color-text-primary`, `lu`
// is `px`, a type size is in `rem` at 16 lu. The first selected theme is the
// root's; every other theme is a `[data-theme=…]` block and, for `dark`,
// also a `prefers-color-scheme: dark` block. CSS is one binding, not the
// source of truth.

export interface Tokens {
  unit?: string;
  themes?: Record<string, Record<string, string>>;
  type?: Record<string, { size: number; weight?: number; line_height?: number }>;
  space?: Record<string, number>;
  radius?: Record<string, number>;
  duration?: Record<string, number>;
  pairs?: { text: string; background: string }[];
}

const name = (token: string): string => `--${token.replace(/\./g, '-')}`;

export function tokensCss(tokens: Tokens): string {
  const themes = Object.entries(tokens.themes ?? {});
  const fixed: string[] = [];
  for (const [k, v] of Object.entries(tokens.type ?? {})) {
    fixed.push(`  ${name(k)}: ${Number(v.size) / 16}rem;`);
    if (v.weight !== undefined) fixed.push(`  ${name(k)}-weight: ${v.weight};`);
    if (v.line_height !== undefined) fixed.push(`  ${name(k)}-line-height: ${v.line_height};`);
  }
  for (const [k, v] of Object.entries(tokens.space ?? {})) fixed.push(`  ${name(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(tokens.radius ?? {})) fixed.push(`  ${name(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(tokens.duration ?? {})) fixed.push(`  ${name(k)}: ${v}ms;`);
  const colours = (vals: Record<string, string>) => Object.entries(vals).map(([k, v]) => `  ${name(k)}: ${v};`);
  const out = ['/* Generated by the engine from tokens.json (D7 B.11); do not edit. */', ':root {', ...(themes[0] ? colours(themes[0][1]) : []), ...fixed, '}'];
  for (const [theme, vals] of themes.slice(1)) {
    out.push(`[data-theme="${theme}"] {`, ...colours(vals), '}');
    if (theme === 'dark') out.push('@media (prefers-color-scheme: dark) {', '  :root {', ...colours(vals).map((l) => `  ${l}`), '  }', '}');
  }
  return `${out.join('\n')}\n`;
}
