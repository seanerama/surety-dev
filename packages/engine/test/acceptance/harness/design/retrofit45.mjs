export const OBSERVED_LOGO_PATH = 'assets/observed/logo.svg';

const targetOf = (inventory, target) => {
  const t = (inventory.targets ?? []).find((x) => x.target === target);
  assert.ok(t, `the inventory has a ${target} target (${JSON.stringify(inventory.targets)})`);
  return t;
};
const fixtureOf = (inventory, o) => {
  const f = (inventory.fixtures ?? []).find((x) => x.interface === o.interface && x.state === o.state);
  return f ? (f.path.startsWith(DESIGN_DIR) ? f.path.slice(DESIGN_DIR.length) : f.path) : null;
};
// The engine's manifest with the logo's `full` variant the repository's logo:
// provenance `observed`, status `proposed` (D7 §12), versions incremented, history kept.
export function observedManifest(manifest) {
  const m = clone(manifest);
  const slot = m.slots.find((s) => s.kind === 'logo');
  assert.ok(slot, `the engine's manifest has a logo slot (${JSON.stringify(m.slots.map((s) => s.key))})`);
  slot.variants = slot.variants.map((v) => (v.name === 'full' ? { name: 'full', format: 'svg', transparency: v.transparency ?? 'any', file: OBSERVED_LOGO_PATH, digest: sha256hex(LOGO_SVG) } : v));
  slot.slot_version += 1;
  slot.status = 'proposed';
  slot.provenance = 'observed';
  slot.status_since = 1;
  slot.history = [...(slot.history ?? []), { slot_version: slot.slot_version, design_version: 1, status: 'proposed', files: slot.variants.filter((v) => v.digest).map((v) => ({ variant: v.name, digest: v.digest })) }];
  m.version += 1;
  return m;
}

// The observed design as {path under .surety/design/: text}: S1 the sum page
// (`/`, sum-route and history-feed), S2 the history page (`/history`,
// history-feed), each mockup a copy of its page. `unknownBack`: S2's
// `browser_back` written `unknown` (the code does not show it, D7 §12).
export function observedDesign(inventory, manifest, { unknownBack = false } = {}) {
  const web = targetOf(inventory, 'web');
  const obligations = (inventory.obligations ?? []).filter((o) => o.target === 'web');
  const stateOf = (o, mockup) => ({ obligation: o, mockup, ...(fixtureOf(inventory, o) ? { fixture: fixtureOf(inventory, o) } : {}) });
  const s1Mockup = 'mockups/web/s1.html';
  const s2Mockup = 'mockups/web/s2.html';
  const screens = [
    {
      key: 'S1',
      target: 'web',
      title: 'Sums',
      flow_steps: ['F1.1'],
      // The conformance stage carries every module, the web module among
      // them, so each requirement it implements is a UI requirement of the
      // inventory (D7 §4.2; objection 150): the sum page, the service's front
      // page, is where the observed design shows R1 to R3.
      requirements: ['R1', 'R2', 'R3', 'R5'],
      interfaces: ['sum-route', 'history-feed'],
      states: obligations.filter((o) => o.interface !== 'history-feed').map((o) => stateOf(o, s1Mockup)),
      layouts: web.layouts,
      inputs: [
        { interface: 'sum-route', property: 'a', label: 'First number' },
        { interface: 'sum-route', property: 'b', label: 'Second number' },
      ],
      conventions: { route: '/', browser_back: 'leaves Sums for the previous page', keyboard_path: 'Tab reaches First number, Second number and Sum in that order' },
    },
    {
      key: 'S2',
      target: 'web',
      title: 'Sums: history',
      flow_steps: ['F1.2'],
      requirements: ['R6'],
      interfaces: ['history-feed'],
      states: obligations.filter((o) => o.interface === 'history-feed').map((o) => stateOf(o, s2Mockup)),
      layouts: web.layouts,
      inputs: [],
      conventions: { route: '/history', browser_back: unknownBack ? 'unknown' : 'returns to the sum page', keyboard_path: 'Tab reaches each link' },
    },
  ];
  const slots = new Map();
  for (const t of inventory.targets ?? []) for (const s of t.required_slots ?? []) slots.set(s.kind, [...new Set([...(slots.get(s.kind) ?? []), ...s.variants])]);
  const design = {
    version: 1,
    origin: 'observed',
    inventory_digest: inventory.inventory_digest,
    selection: { themes: ['light'], slots: [...slots].map(([kind, variants]) => ({ kind, variants })), layouts: [{ target: 'web', layouts: web.layouts }] },
    targets: [{ module: web.module, target: 'web', ui_technology: web.ui_technology, form_factors: [], preview_capability: web.preview_capability, layouts: web.layouts }],
    tokens_file: 'tokens.json',
    flows_file: 'flows.json',
    screens_file: 'screens.json',
    navigation_file: 'navigation.json',
    criteria_file: 'criteria.json',
    assets_file: 'assets/manifest.json',
    mockups: [
      { path: s1Mockup, kind: 'static_html', screens: ['S1'], external_urls: [] },
      { path: s2Mockup, kind: 'static_html', screens: ['S2'], external_urls: [] },
    ],
  };
  const files = {
    'design.json': json(design),
    'tokens.json': json(OBSERVED_TOKENS),
    'flows.json': json({ flows: [{ key: 'F1', title: 'Sum and look back', requirements: ['R1', 'R2', 'R3', 'R5', 'R6'], steps: [{ key: 'F1.1', title: 'Sum two numbers', interfaces: ['sum-route'] }, { key: 'F1.2', title: 'Read the history', interfaces: ['history-feed'] }] }] }),
    'screens.json': json({ screens }),
    'navigation.json': json({ targets: [{ target: 'web', entries: ['S1'], edges: [{ from: 'S1', to: 'S2', trigger: 'open the history', kind: 'push' }] }] }),
    'criteria.json': json({
      criteria: [clone(R5_TOKENS)],
      human_tests: [{ target: 'web', text: 'The web UI matches approved design version 1, as observed from the adopted pages: screens S1 and S2; browser back and the keyboard path are judged by a person.', screens: ['S1', 'S2'], not_checkable_yet: ['S1', 'S2'].flatMap((screen) => ['browser_back', 'keyboard_path'].map((convention) => ({ screen, convention }))) }],
    }),
    'assets/manifest.json': json(observedManifest(manifest)),
    [OBSERVED_LOGO_PATH]: LOGO_SVG,
    [s1Mockup]: PAGE_HTML,
    [s2Mockup]: HISTORY_HTML,
    'design.md': '# Sums: the observed design\n\nCaptured from the adopted pages: their colours, sizes and routes as they are.\n',
  };
  return Object.fromEntries(Object.entries(files).map(([p, t]) => [`${DESIGN_DIR}${p}`, t]));
}
