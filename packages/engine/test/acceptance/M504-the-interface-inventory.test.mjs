// M504, the interface inventory (slice 40; kernel lane). M6 plan §3.2 M504;
// D7 §2, §4.2, §4.4, §5.2; B.9; SEAM.md §§480, 484.
//
// (a) derivation from one bundle twice (two projects with the same bundle),
//     after more ticks, and after a restart: identical inventory.json and
//     inventory_digest; one design.inventory_derived; no second commit;
// (b) obligations per target: an http interface, two declared errors, a
//     `collection` response, a bounded and an enum property, a permission
//     on android, `ok`;
// (c) preview capability: web under html_css, three_js, streamlit,
//     flutter, other; android under react_native; macos under swiftui;
//     `design_preview: off`;
// (d) layouts: `design_widths`; android form factors in
//     `design_orientations`; a desktop target before any design;
// (e) fixtures per interface and state, valid against their shapes;
//     regenerated byte-identical;
// (f) the commit of inventory, fixtures and placeholders, and a kill
//     between the commit and its record;
// (g) `design: off`; `at_alpha`; a project with no `ui` module;
// (h) an interface no `ui` module consumes or exposes.
//
// F5 (an engine finding of the paid M535 run; Sean's ruling 2026-10-19,
// errata E169): interfaces `ui` modules expose with no `request`,
// `response` or `errors`, in a map approved under `design: off` and the
// policy then turned to `before_build`: listed `shape_known: false`, and no
// state obligation (and so no fixture) derived from them, exactly as for
// `shape: "unknown"` (D7 §12: "nothing is derived from it").

