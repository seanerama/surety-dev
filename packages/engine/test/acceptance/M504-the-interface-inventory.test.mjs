const BEFORE_BUILD = Object.freeze({ design: 'before_build', phase_size: { min: 1, max: 5 } });

// ---- the test's own reading of B.8 (never the engine's) ---------------------------------------
function valid(value, shape) {
  if (!shape) return true;
  const types = [shape.type].flat();
  const typeOk = types.some((t) => (t === 'null' ? value === null : t === 'array' ? Array.isArray(value) : t === 'integer' ? Number.isInteger(value) : t === 'object' ? value !== null && typeof value === 'object' && !Array.isArray(value) : typeof value === t));
  if (!typeOk) return false;
  if (value === null) return true;
  if (shape.enum && !shape.enum.includes(value)) return false;
  if (typeof value === 'number' && ((shape.minimum !== undefined && value < shape.minimum) || (shape.maximum !== undefined && value > shape.maximum))) return false;
  if (typeof value === 'string' && ((shape.minLength !== undefined && value.length < shape.minLength) || (shape.maxLength !== undefined && value.length > shape.maxLength))) return false;
  if (Array.isArray(value)) return value.every((v) => valid(v, shape.items));
  if (typeof value === 'object') {
    for (const k of shape.required ?? []) if (!(k in value)) return false;
    for (const [k, v] of Object.entries(value)) if (!shape.properties?.[k] || !valid(v, shape.properties[k])) return false;
  }
  return true;
}

// Pantry with a third UI-consumed interface whose request holds an enum
// property and which only the web module consumes (b).
const SET_SHELF = { name: 'set-shelf', kind: 'http', path: '/api/shelf', description: 'POST /api/shelf {"shelf"} moves the list to a shelf', consumed_by: ['web'], request: { type: 'object', properties: { shelf: { type: 'string', enum: ['dry', 'cold'] } }, required: ['shelf'] }, response: { type: 'null' }, errors: [] };
const WITH_SHELF = { ...MODULES_JSON, modules: MODULES_JSON.modules.map((m) => (m.name === 'api' ? { ...m, interfaces: [...m.interfaces, SET_SHELF] } : m)) };

// The axes map (c), (d): five web modules under each web technology, an
// android module on phone and tablet, a macos module under swiftui.
const AXES_SPEC_MODULES = [...SPEC_MODULES, { name: 'desk', paths: ['desk/'] }];
const webModule = (name, tech) => ({ name, surface: 'ui', paths: [`${name}/`], sensitive_areas: [], targets: [{ target: 'web', ui_technology: tech }], interfaces: [] });
const AXES_MAP = {
  version: 1,
  modules: [
    { ...MODULES_JSON.modules[0], interfaces: [INTERFACES.list, INTERFACES.add].map((i) => ({ ...i, consumed_by: ['web', 'mobile'] })) },
    webModule('web', 'html_css'),
    webModule('web-three', 'three_js'),
    webModule('web-streamlit', 'streamlit'),
    webModule('web-flutter', 'flutter'),
    webModule('web-other', 'other'),
    { ...MODULES_JSON.modules[2], targets: [{ target: 'android', ui_technology: 'react_native', form_factors: ['phone', 'tablet'] }] },
    { name: 'desk', surface: 'ui', paths: ['desk/'], sensitive_areas: [], targets: [{ target: 'macos', ui_technology: 'swiftui' }], interfaces: [] },
  ],
  mapping_from_spec: [
    { spec_module: 'api', to: ['api'] },
    { spec_module: 'web', to: ['web', 'web-three', 'web-streamlit', 'web-flutter', 'web-other'] },
    { spec_module: 'mobile', to: ['mobile'] },
    { spec_module: 'desk', to: ['desk'] },
  ],
};
const AXES_ROADMAP = { ...ROADMAP_JSON, phases: [{ ...ROADMAP_JSON.phases[0], modules: AXES_MAP.modules.map((m) => m.name) }] };
const AXES = { spec: specText({ targets: '**Targets:** web, android, macos', modules: AXES_SPEC_MODULES }), files: { modules: AXES_MAP, roadmap: AXES_ROADMAP } };

const capability = (inventory, module, target) => (inventory.targets ?? []).find((t) => t.module === module && t.target === target)?.preview_capability;
const key = (o) => `${o.target}|${o.interface ?? ''}|${o.permission ?? ''}|${o.state}`;

describe('M504 the interface inventory', () => {
  test('(a), (e) one bundle derived twice, after more ticks and after a restart: identical inventory.json and digest; one design.inventory_derived; no second commit; fixtures valid against their shapes and byte-identical', async (t) => {
    const fx = await scriptedEngine(t);
    const a = (await toPublished(fx, { policy: BEFORE_BUILD })).p;
    const b = (await toPublished(fx, { policy: BEFORE_BUILD, name: 'pantry-b' })).p;
    const invA = inventoryOf(a);
    const invB = inventoryOf(b);
    assert.match(invA.inventory_digest ?? '', /^[0-9a-f]{64}$/, 'inventory_digest');
    assert.equal(gitText(a, INVENTORY_PATH), gitText(b, INVENTORY_PATH), 'the same bundle derives the same inventory.json, byte for byte');
    const bytes = gitText(a, INVENTORY_PATH);
    await tick(fx.engine, a.id, { rounds: 3 });
    await fx.engine.kill();
    await fx.start();
    await tick(fx.engine, a.id, { rounds: 3 });
    assert.equal(gitText(a, INVENTORY_PATH), bytes, 'unchanged after more ticks and a restart');
    assert.equal(designEvents(fx.home, 'design.inventory_derived', a.id).length, 1, 'one design.inventory_derived');
    const carrying = revisionsOfKind(fx.home, a.id, 'intent').filter((r) => r.parent_sha && changedPaths(a.repo.path, r.parent_sha, r.sha)[INVENTORY_PATH]);
    assert.equal(carrying.length, 1, 'no second commit');
    // (e) fixtures.
    const fixtures = invA.fixtures ?? [];
    assert.ok(fixtures.length > 0, 'fixtures listed');
    const ifaceOf = (name) => invA.interfaces.find((i) => i.name === name);
    for (const f of fixtures) {
      assert.match(f.path, new RegExp(`(^|/)inventory/fixtures/${f.interface.replace(/[-.]/g, '\\$&')}\\.${f.state.replace(/[:.]/g, '\\$&')}\\.json$`), `${f.interface} ${f.state}: named <interface>.<state>.json (D7 §4.4)`);
      const path = f.path.startsWith('.surety/design/') ? f.path : `.surety/design/${f.path}`;
      const text = gitText(a, path);
      assert.ok(text !== null, `${path} committed`);
      assert.equal(gitText(b, path), text, `${path}: regenerated byte-identical`);
      const value = JSON.parse(text);
      const i = ifaceOf(f.interface);
      if (f.state === 'ok') assert.ok(valid(value, i.response), `${path}: valid against the response shape (${text})`);
      if (f.state === 'empty') assert.deepEqual(value.items, [], `${path}: the collection empty`);
      if (f.state === 'ok' && f.interface === 'list-items') assert.equal(value.items.length, 3, `${path}: a collection of three`);
      if (f.state.startsWith('error:')) assert.equal(value.code, f.state.slice('error:'.length), `${path}: the declared error (SEAM.md §484)`);
      if (f.state === 'invalid_input') {
        assert.equal(valid(value, i.request), false, `${path}: invalid against the request shape`);
        assert.ok(typeof value.name === 'string' && (value.name.length < 1 || value.name.length > 40), `${path}: violating the first bound (name's length) (${text})`);
        assert.ok(valid(value.quantity, i.request.properties.quantity), `${path}: and only it`);
      }
    }
  });

  test('(b) obligations per target: loading, error:<code> for each, empty, invalid_input (bounded and enum), permission_denied on android only, ok; each naming its interface or permission and its target', async (t) => {
    const fx = await scriptedEngine(t);
    const { p } = await toPublished(fx, { policy: BEFORE_BUILD, files: { modules: WITH_SHELF } });
    const inventory = inventoryOf(p);
    const per = (target, iface, states) => states.map((state) => ({ target, interface: iface, state }));
    const want = [
      ...['web', 'android'].flatMap((target) => [
        ...per(target, 'list-items', ['loading', 'empty', 'ok']),
        ...per(target, 'add-item', ['loading', 'error:name_taken', 'error:invalid_item', 'invalid_input', 'ok']),
      ]),
      ...per('web', 'set-shelf', ['loading', 'invalid_input', 'ok']),
      { target: 'android', permission: 'notifications', state: 'permission_denied:notifications' },
    ];
    assert.deepEqual((inventory.obligations ?? []).map(key).sort(), want.map(key).sort(), `the obligations (SEAM.md §484) (${JSON.stringify(inventory.obligations)})`);
  });

  test('(c), (d) preview capability per target and technology; layouts by default, per form factor and orientation, none for a desktop target before a design; design_preview: off gives none', async (t) => {
    const fx = await scriptedEngine(t);
    const { p } = await toPublished(fx, { policy: BEFORE_BUILD, spec: AXES.spec, files: AXES.files });
    const inv = inventoryOf(p);
    assert.deepEqual(
      [['web', 'web'], ['web-three', 'web'], ['web-streamlit', 'web'], ['web-flutter', 'web'], ['web-other', 'web'], ['mobile', 'android'], ['desk', 'macos']].map(([m, tg]) => capability(inv, m, tg)),
      ['native', 'native', 'simulated', 'simulated', 'simulated', 'simulated', 'simulated'],
      `capabilities (D7 §5.2) (${JSON.stringify(inv.targets?.map((x) => [x.module, x.target, x.preview_capability]))})`,
    );
    const layouts = (m, tg) => (inv.targets ?? []).find((x) => x.module === m && x.target === tg)?.layouts;
    assert.deepEqual(layouts('web', 'web'), [360, 720, 1280], 'design_widths by default');
    assert.deepEqual(layouts('mobile', 'android'), ['phone-portrait', 'phone-landscape', 'tablet-portrait', 'tablet-landscape'], 'each form factor in both orientations (SEAM.md §484)');
    assert.deepEqual(layouts('desk', 'macos'), [], 'a desktop target\'s layouts are the window sizes its design will declare: none yet');
    const off = (await toPublished(fx, { policy: { ...BEFORE_BUILD, design_preview: 'off' }, name: 'pantry-off', spec: AXES.spec, files: AXES.files })).p;
    const invOff = inventoryOf(off);
    assert.deepEqual([...new Set((invOff.targets ?? []).map((x) => x.preview_capability))], ['none'], 'design_preview: off: none everywhere');
  });

  test('(f) inventory, fixtures and placeholders one engine intent revision through the journal, before any Designer session; a kill between the commit and its record: recovery records it once', async (t) => {
    const fx = await scriptedEngine(t);
    const p = await createPantry(fx, { policy: BEFORE_BUILD });
    await pantrySpec(fx, p.id);
    const arch = await pantryArchitect(fx, p.id, p.repo, { answer: 'none' });
    assert.equal(arch.closeRes.status, 200, `the close (${arch.closeRes.text?.slice(0, 400)})`);
    await armBarrier(fx.engine, 'design.inventory_committed', 'pause');
    await consume(fx, p.id, arch.decisions.architecture_approval, 'approve');
    fx.engine.post(`/v1/projects/${p.id}/decisions/${arch.decisions.plan_approval.id}/answer`, { option: 'approve', preview_hash: arch.decisions.plan_approval.preview_hash }).catch(() => null);
    await reachBarrier(fx, p.id, 'design.inventory_committed');
    assert.equal(designEvents(fx.home, 'design.inventory_derived', p.id).length, 0, 'at the barrier: committed, not yet recorded');
    await fx.engine.kill();
    await fx.start();
    await waitPublished(fx, p.id, { max: 10 });
    await tick(fx.engine, p.id, { rounds: 3 });
    assert.equal(designEvents(fx.home, 'design.inventory_derived', p.id).length, 1, 'recovery records it once');
    const intents = revisionsOfKind(fx.home, p.id, 'intent').filter((r) => r.created_by_run === null && r.parent_sha && changedPaths(p.repo.path, r.parent_sha, r.sha)[INVENTORY_PATH]);
    assert.equal(intents.length, 1, 'one engine intent revision');
    const changed = changedPaths(p.repo.path, intents[0].parent_sha, intents[0].sha);
    assert.ok(Object.keys(changed).every((path) => path.startsWith('.surety/design/')), `it touches .surety/design/ only (${Object.keys(changed).join(', ')})`);
    assert.ok(changed[MANIFEST_PATH] && Object.keys(changed).some((x) => x.includes('/inventory/fixtures/')), 'with the fixtures and the placeholders\' manifest');
    const manifest = gitJson(p, MANIFEST_PATH);
    for (const slot of manifest.slots) for (const v of slot.variants) if (v.file) assert.ok(changed[`.surety/design/${v.file}`], `${slot.key} ${v.name}: its placeholder in the same revision`);
    assert.equal(decisionsOfKind(fx.home, p.id, 'design_due').filter((d) => d.status === 'open').length, 1, 'one design_due');
  });

  test('(g) design: off derives nothing; at_alpha derives and holds nothing; no ui module: an inventory with no obligations, nothing raised, GET …/design says inert', async (t) => {
    const fx = await scriptedEngine(t);
    const off = (await toPublished(fx, { policy: { phase_size: { min: 1, max: 5 } }, name: 'pantry-off' })).p;
    assert.equal(gitText(off, INVENTORY_PATH), null, 'off: no inventory');
    assert.equal(designEvents(fx.home, 'design.inventory_derived', off.id).length, 0, 'off: no event');
    const atAlpha = (await toPublished(fx, { policy: { design: 'at_alpha', phase_size: { min: 1, max: 5 } }, name: 'pantry-alpha' })).p;
    assert.ok(inventoryOf(atAlpha).inventory_digest, 'at_alpha: derived');
    assert.equal(openDesignDue(fx.home, atAlpha.id), null, 'at_alpha: nothing raised before build');
    for (const n of [2, 3]) assert.equal(JSON.stringify(stageWork(fx.home, atAlpha.id, n)?.depends_on ?? []).includes('design_ready'), false, `at_alpha: stage ${n} does not wait on design_ready`);
    const tally = await createWithIdea(fx, { name: 'tally-design', policy: { design: 'before_build' } });
    await specSession(fx, tally.id);
    await architectSession(fx, tally.id, tally.repo);
    const inv = gitJson(tally, INVENTORY_PATH);
    assert.ok(inv, 'no ui module: an inventory');
    assert.deepEqual([inv.obligations, inv.ui_requirements], [[], []], 'with no obligations');
    assert.equal(openDesignDue(fx.home, tally.id), null, 'nothing raised');
    const design = await readDesign(fx, tally.id);
    assert.equal(design.inert, true, `GET …/design says the policy is inert (${JSON.stringify(design).slice(0, 300)})`);
    assert.ok(typeof design.inert_reason === 'string' && design.inert_reason.length > 0, 'and why');
  });

  test('(h) an interface no ui module consumes or exposes is not listed', async (t) => {
    const fx = await scriptedEngine(t);
    const { p } = await toPublished(fx, { policy: BEFORE_BUILD });
    const names = (inventoryOf(p).interfaces ?? []).map((i) => i.name).sort();
    assert.deepEqual(names, ['add-item', 'list-items'], `health is not listed (${names})`);
  });
  test('F5 (errata E169): ui modules exposing interfaces with no request, response or errors, the map approved under off and the policy turned to before_build: listed shape_known false, no obligation and no fixture derived from them', async (t) => {
    const fx = await scriptedEngine(t);
    const { p } = await toPublished(fx, { policy: { phase_size: { min: 1, max: 5 } }, name: 'pantry-exposed', files: { modules: modulesExposing({ web: [EXPOSED.page], mobile: [EXPOSED.apiBaseUrl] }) } });
    assert.equal(gitText(p, INVENTORY_PATH), null, 'the fixture is live: no inventory under off');
    await changePolicy(fx.engine, p.id, { design: 'before_build' });
    for (let i = 0; i < 6 && designEvents(fx.home, 'design.inventory_derived', p.id).length === 0; i++) await tick(fx.engine, p.id, { rounds: 1 });
    assert.equal(designEvents(fx.home, 'design.inventory_derived', p.id).length, 1, 'the fixture is live: the inventory derived on the policy revision');
    const inventory = inventoryOf(p);
    const UNSHAPED = [['page', 'web'], ['api_base_url', 'mobile']];
    for (const [name, module] of UNSHAPED) {
      const f = (inventory.interfaces ?? []).find((i) => i.name === name);
      assert.ok(f, `${name}, which ${module} exposes, is listed (D7 §4.2) (${JSON.stringify(inventory.interfaces)})`);
      assert.equal(f.module, module, `${name}: its module`);
      assert.equal(f.shape_known, false, `${name}: shape_known false (B.9)`);
      assert.ok(f.request === undefined && f.response === undefined, `${name}: no shape invented (${JSON.stringify(f)})`);
    }
    for (const target of ['web', 'android']) for (const name of ['list-items', 'add-item']) assert.ok((inventory.obligations ?? []).some((o) => o.target === target && o.interface === name && o.state === 'ok'), `the shaped interfaces still derive their obligations: ${name} ok on ${target}`);
    for (const [name] of UNSHAPED) {
      assert.deepEqual((inventory.obligations ?? []).filter((o) => o.interface === name), [], `${name}: no state obligation derived from an interface whose shape is not known (F5; Sean's ruling 2026-10-19, errata E169) (${JSON.stringify((inventory.obligations ?? []).filter((o) => o.interface === name))})`);
      assert.deepEqual((inventory.fixtures ?? []).filter((x) => x.interface === name), [], `${name}: no fixture generated for it`);
    }
  });
});

