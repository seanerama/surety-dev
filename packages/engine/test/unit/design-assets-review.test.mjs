// ---- B1: the activity check ------------------------------------------------------------------

// The Verifier's passive SVG (test/acceptance/harness/design/assets43.mjs `passiveSvg`), copied.
const passiveSvg = (w, h, label = 'Pantry') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}"><rect width="${w}" height="${h}" fill="#2e7d32"/><text x="${w / 2}" y="${h / 2}" text-anchor="middle" fill="#ffffff">${label}</text></svg>\n`;
const SVG = 'xmlns="http://www.w3.org/2000/svg"';
// The review's twelve bypasses of the slice-43 check, each passing it at b34bcfc.
const ACTIVE = {
  'a prefixed script bound to the SVG namespace': `<svg ${SVG} xmlns:s="http://www.w3.org/2000/svg"><s:script>alert(1)</s:script></svg>`,
  'an XHTML script under its own prefix': `<svg ${SVG}><h:script xmlns:h="http://www.w3.org/1999/xhtml">alert(1)</h:script></svg>`,
  'an iframe with a data: HTML document': `<svg ${SVG}><iframe src="data:text/html;base64,PHNjcmlwdD5hbGVydCgxKTwvc2NyaXB0Pg=="/></svg>`,
  'a srcdoc holding an escaped script': `<svg ${SVG}><g srcdoc="&lt;script&gt;alert(1)&lt;/script&gt;"/></svg>`,
  'an ISO-2022-JP declaration hiding a script': Buffer.concat([Buffer.from(`<?xml version="1.0" encoding="ISO-2022-JP"?><svg ${SVG}>`), Buffer.from([0x1b, 0x28, 0x4a]), Buffer.from('<script>alert(1)</script></svg>')]),
  'an xml-stylesheet processing instruction': `<?xml-stylesheet type="text/xsl" href="data:text/xsl,x"?><svg ${SVG}><rect width="1" height="1"/></svg>`,
  'a CSS @import of an external sheet': `<svg ${SVG}><style>@import url(https://example.org/a.css);</style><rect width="1" height="1"/></svg>`,
  'a style attribute filling from an external url()': `<svg ${SVG}><rect width="1" height="1" style="fill:url(https://example.org/p.svg#g)"/></svg>`,
  'an animation setting href to a script URL': `<svg ${SVG}><a href="#x"><animate attributeName="href" values="javascript:alert(1)"/><text>x</text></a></svg>`,
  'a set of xlink:href to an entity-encoded script URL': `<svg ${SVG} xmlns:xlink="http://www.w3.org/1999/xlink"><a xlink:href="#x"><set attributeName="xlink:href" to="&#106;avascript:alert(1)"/></a></svg>`,
  'a DOCTYPE declaring an entity': `<!DOCTYPE svg [<!ENTITY x "y">]><svg ${SVG}><text>&x;</text></svg>`,
  'a UTF-16 byte-order mark': Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(`<svg ${SVG}><script>alert(1)</script></svg>`, 'utf16le')]),
};

test('B1: each of the review\'s twelve active SVGs is refused, by name; the passive SVG and the engine\'s placeholders are admitted', () => {
  for (const [name, text] of Object.entries(ACTIVE)) {
    const bytes = Buffer.isBuffer(text) ? text : Buffer.from(text);
    assert.equal(formatOf(bytes), 'svg', `${name}: read as an SVG, so the activity check judges it`);
    const why = svgActive(bytes);
    assert.notEqual(why, null, `${name}: refused`);
    const reasons = headerReasons(bytes, { format: 'svg', transparency: 'any' }, { slot: 'logo', variant: 'full', file: 'f.svg' });
    assert.deepEqual(reasons.map((r) => r.code), ['DESIGN_ASSET_SVG_ACTIVE'], `${name}: DESIGN_ASSET_SVG_ACTIVE (${why})`);
  }
  assert.equal(svgActive(Buffer.from(passiveSvg(120, 40, 'Pantry, the household list'))), null, 'passiveSvg is admitted');
  const ph = placeholderManifest('larder-box', ['web', 'android', 'ios']);
  for (const [file, text] of Object.entries(ph.files)) assert.equal(svgActive(Buffer.from(text)), null, `the placeholder ${file} is admitted`);
  // Inside the document, and data: images in an <image>, stay admitted.
  assert.equal(svgActive(`<?xml version="1.0" encoding="UTF-8"?><svg ${SVG} xmlns:xlink="http://www.w3.org/1999/xlink"><defs><linearGradient id="g"/></defs><rect fill="url(#g)" width="1" height="1"/><use xlink:href="#g"/><image href="data:image/png;base64,AAAA" width="1" height="1"/></svg>`), null);
  assert.notEqual(svgActive(`<svg ${SVG}><use href="data:image/png;base64,AAAA"/></svg>`), null, 'data: only in an <image> or <feImage>');
  assert.notEqual(svgActive(`<svg ${SVG}><image href="data:image/svg+xml;base64,AAAA"/></svg>`), null, 'data: only for PNG, JPEG, WebP or GIF');
});

// ---- S1 and the notes: the declaration and the unreadable header -------------------------------

test('S1: an SVG declared forbidden or required is refused with transparency unknown; transparency and a raster\'s size are validated; an unreadable header says why', () => {
  const svg = Buffer.from(passiveSvg(48, 48));
  for (const t of ['forbidden', 'required']) {
    const r = headerReasons(svg, { format: 'svg', transparency: t }, { slot: 's' });
    assert.deepEqual(r.map((x) => x.code), ['DESIGN_ASSET_TRANSPARENCY_MISMATCH']);
    assert.deepEqual(r[0].subjects.found, { unknown: 'transparency is not established for SVG' });
  }
  assert.deepEqual(headerReasons(svg, { format: 'svg', transparency: 'opaque' }, { slot: 's' }).map((x) => [x.code, x.subjects.field]), [['DESIGN_SCHEMA_INVALID', 'transparency']]);
  const cut = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 13]);
  assert.deepEqual(headerReasons(cut, { format: 'png', transparency: 'any' }, { slot: 's' }).map((x) => [x.code, x.subjects.field ?? null]), [
    ['DESIGN_SCHEMA_INVALID', 'size'],
    ['DESIGN_ASSET_SIZE_MISMATCH', null],
  ]);
  const unread = headerReasons(cut, { format: 'png', size: { w: 48, h: 48 }, transparency: 'any' }, { slot: 's', file: 'cut.png' });
  assert.equal(unread[0].code, 'DESIGN_ASSET_SIZE_MISMATCH');
  assert.match(unread[0].subjects.found.unknown, /IHDR/);
  assert.equal(unread[0].subjects.file, 'cut.png');
});

// ---- B2, S2, S3: scratch stores -----------------------------------------------------------------

const P = 'proj_assets';
const INVENTORY = (targets) => JSON.stringify({ inventory_digest: 'dg', targets: targets.map((t) => ({ module: 'ui', target: t, required_slots: [] })), ui_requirements: [], interfaces: [], obligations: [], fixtures: [], cross_platform: false });

function scratch(t) {
  const dir = mkdtempSync(join(tmpdir(), 'surety-unit-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const db = new Database(join(dir, 'store.db'));
  t.after(() => db.close());
  migrate(db, join(dist, '..', 'migrations'));
  db.pragma('foreign_keys = OFF');
  setEngineSettings({ lease_ttl: 90, git_deadline: 60, decision_targets: {}, domain_memory_max: 8 * 1024 ** 3, max_concurrent_domains: 8 });
  const at = new Date().toISOString();
  db.prepare(`INSERT INTO "projects" ("id", "created_at", "name", "tier", "dev_repo_path", "integration_branch", "baseline_state", "registration_state", "management") VALUES (?, ?, 'pantry', 'T2', '/nowhere', 'main', 'spec_ready', 'registered', 'x')`).run(P, at);
  return { db, at };
}
// The record a derivation makes (design/driver.ts): the placeholders alone, never the head's manifest.
const recordOf = (targets, headManifest = 'unchanged') => ({ ...placeholderManifest('pantry', targets).manifest, sources: {}, head_manifest: headManifest });
let n = 0;
function derive(db, at, targets, record) {
  const id = `dinv_${++n}`;
  db.prepare(`INSERT INTO "design_inventories" ("id", "created_at", "project", "inventory_digest", "revision", "inventory", "manifest") VALUES (?, ?, ?, ?, ?, ?, ?)`).run(id, at, P, `dg${n}`, `r${n}`, INVENTORY(targets), JSON.stringify(record));
  transact(db, ENGINE_ACTOR, (tx) => recordInventory(tx, { id }));
}
const effective = (db) => db.prepare('SELECT "slot", "variant", "source", "digest", "slot_version", "platforms" FROM "design_effective_assets" WHERE "project" = ? ORDER BY "slot", "variant"').all(P);

// The head's manifest as a Designer left it: a banner proposed, and the logo's platforms narrowed to web.
function designerHead(targets) {
  const m = structuredClone(placeholderManifest('pantry', targets).manifest);
  m.slots.find((s) => s.kind === 'logo').platforms = ['web'];
  m.slots.push({ key: 'banner', kind: 'banner', purpose: 'hero', platforms: ['web'], placement: 'website_hero', alt_text: 'b', variants: [{ name: 'default', format: 'svg', transparency: 'any', file: 'assets/m/banner.svg', digest: 'b'.repeat(64) }], slot_version: 1, status: 'proposed', provenance: 'designer', status_since: 1, history: [] });
  m.version = 2;
  return m;
}

test('B2: a re-derivation over a Designer\'s manifest records the placeholders alone: the proposed banner never becomes effective (before and after an approval) and the save never moves an effective platform', (t) => {
  const { db, at } = scratch(t);
  derive(db, at, ['web', 'android'], recordOf(['web', 'android'], 'absent'));
  // The Designer's manifest at the head; android added later: the plan merges, the record is the placeholders.
  const head = designerHead(['web', 'android']);
  const plan = placeholderPlan(JSON.stringify(head), placeholderManifest('pantry', ['web', 'android', 'ios']), 'h1');
  assert.equal(plan.head_manifest, 'merged');
  const written = JSON.parse(plan.files['assets/manifest.json']);
  assert.ok(written.slots.some((s) => s.key === 'banner'), 'the head\'s banner kept in the manifest written');
  derive(db, at, ['web', 'android', 'ios'], recordOf(['web', 'android', 'ios'], plan.head_manifest));
  let rows = effective(db);
  assert.ok(!rows.some((r) => r.slot === 'banner'), 'no banner effective before an approval');
  assert.deepEqual(JSON.parse(rows.find((r) => r.slot === 'logo').platforms).sort(), ['android', 'ios', 'web'], 'the logo\'s platforms are the derivation\'s, not the save\'s');
  assert.ok(rows.some((r) => r.slot === 'splash' && r.source === 'placeholder'), 'ios\'s splash placeholder effective');
  // Approved with the banner held.
  const manifest = designerHead(['web', 'android', 'ios']);
  db.prepare(
    `INSERT INTO "design_revisions" ("id", "created_at", "project", "version", "scope", "revision", "blobs", "origin", "targets", "asset_manifest", "selection", "narrowings", "status", "findings", "assets_held")
     VALUES ('dsg_1', ?, ?, 1, 'full', 'r9', '{}', 'intended', '[]', ?, ?, '[]', 'proposed', '[]', '["banner"]')`,
  ).run(at, P, JSON.stringify(manifest), JSON.stringify({ themes: ['light'], slots: [{ kind: 'logo', variants: ['full'] }, { kind: 'banner', variants: ['default'] }, { kind: 'favicon', variants: ['default'] }, { kind: 'app_icon', variants: ['default'] }, { kind: 'splash', variants: ['default'] }], layouts: [] }));
  transact(db, ENGINE_ACTOR, (tx) => approveDesign(tx, { revision: 'dsg_1', specRevision: null, withoutCriteria: true }));
  assert.ok(!effective(db).some((r) => r.slot === 'banner'), 'the held banner is not effective after the approval');
  // A later re-derivation over the same head: still no banner, the platforms still the derivation's.
  derive(db, at, ['web', 'android', 'ios'], recordOf(['web', 'android', 'ios']));
  rows = effective(db);
  assert.ok(!rows.some((r) => r.slot === 'banner'), 'no banner after a re-derivation');
  assert.deepEqual(JSON.parse(rows.find((r) => r.slot === 'logo').platforms).sort(), ['android', 'ios', 'web']);
  // An unreadable head manifest: nothing merged, the reason recorded as unknown.
  const bad = placeholderPlan('{"slots": 3}', placeholderManifest('pantry', ['web']), 'h2');
  assert.deepEqual(bad.files, {});
  assert.match(bad.head_manifest.unknown, /not a readable asset manifest/);
});

test('S2: an approval never approves an engine placeholder, and a slot whose file did not change gets no asset_updated work; a save keeping it approved is not forged', (t) => {
  const { db, at } = scratch(t);
  const record = recordOf(['web', 'android']);
  derive(db, at, ['web', 'android'], record);
  const A = 'a'.repeat(64);
  // logo/full approved earlier at slot_version 2.
  db.prepare(`UPDATE "design_effective_assets" SET "source" = 'approved', "digest" = ?, "slot_version" = 2 WHERE "project" = ? AND "slot" = 'logo' AND "variant" = 'full'`).run(A, P);
  // The slot as the head now holds it: the engine extended it (slot_version 3); full still A; compact the placeholder.
  const manifest = structuredClone(record);
  delete manifest.sources;
  delete manifest.head_manifest;
  const logo = manifest.slots.find((s) => s.kind === 'logo');
  logo.variants.find((v) => v.name === 'full').digest = A;
  logo.variants.find((v) => v.name === 'full').file = 'assets/m/logo.svg';
  Object.assign(logo, { slot_version: 3, status: 'proposed', provenance: 'designer' });
  db.prepare(
    `INSERT INTO "design_revisions" ("id", "created_at", "project", "version", "scope", "revision", "blobs", "origin", "targets", "asset_manifest", "selection", "narrowings", "status", "findings")
     VALUES ('dsg_2', ?, ?, 2, 'full', 'r9', '{}', 'intended', '[]', ?, NULL, '[]', 'proposed', '[]')`,
  ).run(at, P, JSON.stringify(manifest));
  transact(db, ENGINE_ACTOR, (tx) => approveDesign(tx, { revision: 'dsg_2', specRevision: null, withoutCriteria: true }));
  const rows = effective(db);
  const ph = record.slots.find((s) => s.kind === 'logo').variants.find((v) => v.name === 'compact').digest;
  assert.deepEqual(['source', 'digest'].map((k) => rows.find((r) => r.slot === 'logo' && r.variant === 'compact')[k]), ['placeholder', ph], 'the placeholder variant is not approved');
  assert.deepEqual(['source', 'digest', 'slot_version'].map((k) => rows.find((r) => r.slot === 'logo' && r.variant === 'full')[k]), ['approved', A, 3], 'full unchanged, its version followed');
  assert.equal(db.prepare(`SELECT COUNT(*) AS n FROM "events" WHERE "type" = 'design.assets_approved'`).get().n, 0, 'nothing moved');
  assert.equal(db.prepare(`SELECT COUNT(*) AS n FROM "work_items" WHERE "kind" = 'fix'`).get().n, 0, 'no asset_updated work');
  // The save that keeps the slot approved with the engine's placeholder variants in it.
  const saved = structuredClone(manifest);
  Object.assign(saved.slots.find((s) => s.kind === 'logo'), { status: 'approved' });
  const files = new Map([['assets/manifest.json', Buffer.from(JSON.stringify(saved))]]);
  const ctx = { inventory: null, externalHosts: [], approved: [{ slot: 'logo', slot_version: 2, digests: { full: A } }], base: null, placeholders: record };
  assert.ok(!checkDesign({ files }, ctx).reasons.some((r) => r.code === 'DESIGN_ASSET_STATUS_FORGED'), 'not STATUS_FORGED');
  const forged = structuredClone(saved);
  forged.slots.find((s) => s.kind === 'logo').variants.find((v) => v.name === 'compact').digest = 'c'.repeat(64);
  assert.ok(checkDesign({ files: new Map([['assets/manifest.json', Buffer.from(JSON.stringify(forged))]]) }, ctx).reasons.some((r) => r.code === 'DESIGN_ASSET_STATUS_FORGED'), 'a file of its own never approved is forged');
});

test('S3: the hook refuses an unknown policy, never met; a slot a later target added is selected', (t) => {
  const { db, at } = scratch(t);
  derive(db, at, ['web'], recordOf(['web']));
  const manifest = placeholderManifest('pantry', ['web']).manifest;
  db.prepare(
    `INSERT INTO "design_revisions" ("id", "created_at", "project", "version", "scope", "revision", "blobs", "origin", "targets", "asset_manifest", "selection", "narrowings", "status", "findings")
     VALUES ('dsg_1', ?, ?, 1, 'full', 'r9', '{}', 'intended', '[]', ?, ?, '[]', 'approved', '[]')`,
  ).run(at, P, JSON.stringify(manifest), JSON.stringify({ themes: ['light'], slots: [{ kind: 'logo', variants: ['full'] }, { kind: 'favicon', variants: ['default'] }], layouts: [] }));
  derive(db, at, ['web', 'ios'], recordOf(['web', 'ios']));
  const sel = selectedSlots(db, P);
  assert.ok(sel.some((s) => s.key === 'splash' && s.platforms.includes('ios')), `ios's splash selected (${JSON.stringify(sel)})`);
  assert.ok(sel.some((s) => s.key === 'app_icon'), 'ios\'s app_icon selected');
  assert.deepEqual(evaluateReleaseHook(db, { project: P, tier: 'live', targets: ['ios'] }, 'unit').reasons[0].subjects, ['app_icon', 'logo', 'splash']);
  db.prepare(`INSERT INTO "policy_revisions" ("id", "created_at", "project", "revision", "git_path", "git_blob", "changed_by", "changed_at", "diff_summary", "widens_authority", "committed", "effective") VALUES ('pol_1', ?, ?, 1, '.surety/policy.json', 'b', 'human', ?, '{}', 0, 1, ?)`).run(
    at,
    P,
    at,
    JSON.stringify({ assets_required_for: 'alpha' }),
  );
  db.prepare('UPDATE "projects" SET "policy_revision" = ? WHERE "id" = ?').run('pol_1', P);
  assert.throws(() => evaluateReleaseHook(db, { project: P, tier: 'beta' }, 'unit'), (e) => e.code === 'policy_unknown');
});

test('a verifying asset_updated fix with no stage to answer to is held with a reason, never completed', (t) => {
  const { db, at } = scratch(t);
  db.prepare(
    `INSERT INTO "work_items" ("id", "created_at", "project", "seq", "kind", "subject", "status", "trigger_source", "trigger_id", "trigger_generation", "repair_attempts", "no_progress_count", "preflight_refusals", "dispatch_hold", "repair_due", "chain")
     VALUES ('wi_fix', ?, ?, 1, 'fix', ?, 'verifying', 'asset_updated', 'x', 1, 0, 0, 0, 0, 0, 0)`,
  ).run(at, P, JSON.stringify({ cause: 'asset_updated', slot: 'logo', bindings: [{ stage: null, target: 'web', path: 'web/logo.svg', form: 'copy' }] }));
  transact(db, ENGINE_ACTOR, (tx) => completeAssetFixes(tx, P));
  const w = db.prepare('SELECT "status", "blocker" FROM "work_items" WHERE "id" = ?').get('wi_fix');
  assert.equal(w.status, 'held');
  assert.equal(JSON.parse(w.blocker).reason, 'asset_fix_ungated');
});
