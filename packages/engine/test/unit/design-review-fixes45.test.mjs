// Developer tests for the slice-45 review's findings: a verdict's
// provenance only from its own review's evidence (B1); design_verdicts
// raised for a review with no verdict except a first design's (B2); the
// answer batch carrying edits, strikes and a severity and refusing an
// unknown field (B3); routes as request paths (S1); evidence sizes judged
// before any decoding and the body cap below the longest string (S4);
// owner evidence's runtimes and a browser never accepting a native target
// (S7); `observed_on` with no evidence refused (N10). Against a scratch
// store and generated bytes; nothing runs.

import assert from 'node:assert/strict';
import { constants as bufferConstants } from 'node:buffer';
import { EventEmitter } from 'node:events';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const dist = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'dist');
const { migrate } = await import(join(dist, 'store', 'migrate.js'));
const { transact, ENGINE_ACTOR } = await import(join(dist, 'store', 'transitions', 'tx.js'));
const { setEngineSettings } = await import(join(dist, 'store', 'transitions', 'settings.js'));
const { raiseQuestion, answerBatch } = await import(join(dist, 'store', 'transitions', 'queue.js'));
const { recordReview, verdictProvenance, humanTestEvidence, isRequestPath, DESIGN_VERDICTS } = await import(join(dist, 'design', 'review.js'));
const { checkEvidence, REVIEW_BODY_CAP, base64Size } = await import(join(dist, 'design', 'evidence.js'));
const { checkDesign } = await import(join(dist, 'design', 'check.js'));
const { readJsonBody } = await import(join(dist, 'api', 'boundary.js'));
const { default: Database } = await import('better-sqlite3');

const P = 'proj_r45';
const HUMAN = { actor_kind: 'human', actor_id: null, request_id: null };

function scratch(t) {
  const dir = mkdtempSync(join(tmpdir(), 'surety-unit-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const db = new Database(join(dir, 'store.db'));
  t.after(() => db.close());
  migrate(db, join(dist, '..', 'migrations'));
  db.pragma('foreign_keys = OFF');
  setEngineSettings({ lease_ttl: 90, git_deadline: 60, decision_targets: {}, domain_memory_max: 8 * 1024 ** 3, max_concurrent_domains: 8 });
  const at = new Date().toISOString();
  db.prepare(`INSERT INTO "projects" ("id", "created_at", "name", "tier", "dev_repo_path", "integration_branch", "baseline_state", "registration_state", "management") VALUES (?, ?, 'pantry', 'T2', '/nowhere', 'main', 'spec_ready', 'registered', 'x')`).run(P, at);
  const review = (id, verdicts, run = `run_${id}`) =>
    db.prepare(`INSERT INTO "design_reviews" ("id", "created_at", "project", "run", "trigger", "subject", "review_blob", "verdicts") VALUES (?, ?, ?, ?, 'owner_command', '{"kind":"owner_build","target":"android","build_ref":"b"}', 'blob', ?)`).run(id, at, P, run, JSON.stringify(verdicts));
  const evidence = (id, review, provenance) =>
    db.prepare(`INSERT INTO "design_evidence" ("id", "created_at", "project", "review", "provenance", "target") VALUES (?, ?, ?, ?, ?, 'web')`).run(id, at, P, review, provenance);
  return { db, at, review, evidence, tx: (fn, actor = ENGINE_ACTOR) => transact(db, actor, fn) };
}
const verdict = (screen, extra = {}) => ({ target: 'web', screen, verdict: 'matches', status: 'proposed', observed_on: 'browser', evidence: [], deltas: [], ...extra });

test('B1: a verdict citing another review\'s engine-observed evidence is never engine-observed', (t) => {
  const { db, review, evidence } = scratch(t);
  review('drv_a', []);
  review('drv_b', []);
  evidence('dev_a', 'drv_a', 'engine_observed');
  evidence('dev_b', 'drv_b', 'owner_supplied');
  assert.equal(verdictProvenance(db, { evidence: ['dev_a'] }, 'drv_a'), 'engine_observed', 'its own review\'s');
  assert.equal(verdictProvenance(db, { evidence: ['dev_a'] }, 'drv_b'), 'owner_reported', 'another review\'s lends nothing');
  assert.equal(verdictProvenance(db, { evidence: ['dev_a', 'dev_b'] }, 'drv_b'), 'owner_supplied');
});

test('B2: a review with no verdict asks design_verdicts, saying so; a first design\'s with none asks nothing', (t) => {
  const { db, tx } = scratch(t);
  const made = tx((x) => recordReview(x, { project: P, run: 'run_1', design_revision: 'dsg_1', trigger: 'alpha_complete', subject: {}, review_blob: 'b1', verdicts: [], review_path: '.surety/design/reviews/review-1.json', first_design: false }));
  assert.ok(made.decision, 'design_verdicts raised');
  const d = db.prepare('SELECT "question" FROM "decisions" WHERE "id" = ?').get(made.decision);
  assert.match(d.question, /holds no verdicts/);
  const first = tx((x) => recordReview(x, { project: P, run: 'run_2', design_revision: null, trigger: 'alpha_complete', subject: {}, review_blob: 'b2', verdicts: [], review_path: '.surety/design/reviews/review-2.json', first_design: true }));
  assert.equal(first.decision, null, 'a first design with no verdict: its approval is the act');
});

test('N7: a review of the same file again invalidates the first one\'s open question', (t) => {
  const { db, tx } = scratch(t);
  const path = '.surety/design/reviews/review-1.json';
  const one = tx((x) => recordReview(x, { project: P, run: 'run_1', design_revision: 'dsg_1', trigger: 'owner_command', subject: {}, review_blob: 'b1', verdicts: [verdict('S1')], review_path: path }));
  const two = tx((x) => recordReview(x, { project: P, run: 'run_2', design_revision: 'dsg_1', trigger: 'owner_command', subject: {}, review_blob: 'b2', verdicts: [verdict('S1')], review_path: path }));
  assert.equal(db.prepare('SELECT "status" FROM "decisions" WHERE "id" = ?').get(one.decision).status, 'invalidated');
  assert.equal(db.prepare('SELECT "status" FROM "decisions" WHERE "id" = ?').get(two.decision).status, 'open');
});

test('B3: the answer batch carries strikes and a severity to design_verdicts, and refuses an unknown field by name', (t) => {
  const { db, review, tx } = scratch(t);
  review('drv_1', [verdict('S1', { verdict: 'deltas', deltas: [{ owner_words: 'the heading is missing', kind: 'implementation' }] }), verdict('S3')]);
  const d = tx((x) => raiseQuestion(x, { project: P, kind: 'design_verdicts', subjectType: 'design_review', subjectId: 'drv_1' }));
  assert.ok(d, 'design_verdicts raised');
  assert.throws(
    () => tx((x) => answerBatch(x, { project: P, answers: [{ decision: d.id, option: 'confirm', preview_hash: d.preview_hash, strike: [] }] }), HUMAN),
    (err) => err.code === 'unknown_field' && err.subject.field === 'answers[0].strike',
  );
  const r = tx((x) => answerBatch(x, { project: P, answers: [{ decision: d.id, option: 'confirm', preview_hash: d.preview_hash, strikes: [{ target: 'web', screen: 'S3' }], severity: 'high' }] }), HUMAN);
  assert.equal(r.status, 200);
  const row = db.prepare('SELECT "verdicts", "findings" FROM "design_reviews" WHERE "id" = ?').get('drv_1');
  const verdicts = JSON.parse(row.verdicts);
  assert.deepEqual(verdicts.map((v) => [v.screen, v.status]), [['S1', 'confirmed'], ['S3', 'struck']]);
  const [finding] = JSON.parse(row.findings);
  assert.equal(db.prepare('SELECT "proposed_severity" FROM "findings" WHERE "id" = ?').get(finding).proposed_severity, 'high');
  void DESIGN_VERDICTS;
});

test('S1: a route is a request path; anything with a space, CR, LF or control is refused by the check', () => {
  for (const ok of ['/', '/web/big.html', '/a?b=c']) assert.equal(isRequestPath(ok), true, ok);
  for (const bad of ['', 'web', '/a b', '/a\r\nHost: x', '/\u0000', '/é']) assert.equal(isRequestPath(bad), false, JSON.stringify(bad));
  const screens = { screens: [{ key: 'S1', target: 'web', title: 't', flow_steps: [], requirements: [], interfaces: [], states: [], layouts: [], inputs: [], conventions: { route: '/a\r\nX: y' } }] };
  const out = checkDesign({ files: new Map([['screens.json', Buffer.from(JSON.stringify(screens))]]) }, { inventory: null, externalHosts: [], approved: [] });
  assert.ok(out.reasons.some((r) => r.code === 'DESIGN_SCHEMA_INVALID' && r.subjects.field === 'screens[0] (S1).conventions.route'));
});

test('S4: sizes judged from the base64 length, nothing past a bound decoded; the body cap below the longest string', () => {
  assert.equal(base64Size(Buffer.alloc(10).toString('base64')), 10);
  assert.equal(base64Size(Buffer.alloc(11).toString('base64')), 11);
  assert.equal(base64Size(Buffer.alloc(12).toString('base64')), 12);
  const never = () => {
    throw new Error('decoded');
  };
  const big = checkEvidence([{ name: 'big.png', size: 2048, bytes: never }], { file: 1024, review: 1 << 20 });
  assert.equal(big.ok, false);
  const together = checkEvidence([1, 2].map((i) => ({ name: `p${i}.png`, size: 800, bytes: never })), { file: 1024, review: 1000 });
  assert.equal(together.ok, false);
  assert.ok(REVIEW_BODY_CAP < bufferConstants.MAX_STRING_LENGTH, `${REVIEW_BODY_CAP} below ${bufferConstants.MAX_STRING_LENGTH}`);
});

test('S4: a body past its cap is refused 413 and settles, a declared length or a stream alike', async () => {
  const req = (headers) => Object.assign(new EventEmitter(), { headers });
  await assert.rejects(readJsonBody(req({ 'content-length': '2048' }), 1024, 5000), (err) => err.status === 413);
  const r = req({});
  const p = readJsonBody(r, 1024, 5000);
  r.emit('data', Buffer.alloc(800));
  r.emit('data', Buffer.alloc(800));
  r.emit('end');
  await assert.rejects(p, (err) => err.status === 413);
});

test('S7: a confirmed matches seen in a browser never accepts a native target; on a device it does', (t) => {
  const { db, at } = scratch(t);
  const confirmed = (id, target, observed_on) =>
    db
      .prepare(`INSERT INTO "design_reviews" ("id", "created_at", "project", "design_revision", "run", "trigger", "subject", "verdicts", "confirmation_decision") VALUES (?, ?, ?, 'dsg_1', ?, 'owner_command', '{"kind":"owner_build","target":"android","build_ref":"b1"}', ?, 'dec_x')`)
      .run(id, at, P, `run_${id}`, JSON.stringify([{ target, screen: 'S2', verdict: 'matches', status: 'confirmed', observed_on, evidence: [], deltas: [] }]));
  confirmed('drv_1', 'android', 'browser');
  assert.equal(humanTestEvidence(db, P, 'android', 'dsg_1', ['S2']).accepted, false);
  confirmed('drv_2', 'android', 'device');
  assert.equal(humanTestEvidence(db, P, 'android', 'dsg_1', ['S2']).accepted, true);
});

// H2 (E171 item 5; SEAM.md §553): every screen of the target, on the newest
// reviewed build of the version in force, the latest counting verdict per
// screen of that build deciding.
test('H2: a human test is accepted only when every screen of the target matches on the newest reviewed build', (t) => {
  const { db, at } = scratch(t);
  let n = 0;
  const v = (screen, verdict, observed_on, extra = {}) => ({ target: 'android', screen, verdict, status: 'confirmed', observed_on, evidence: [], deltas: [], ...extra });
  const confirmed = (subject, verdicts, { revision = 'dsg_1', decision = 'dec_x' } = {}) => {
    n += 1;
    db.prepare(`INSERT INTO "design_reviews" ("id", "created_at", "project", "design_revision", "run", "trigger", "subject", "verdicts", "confirmation_decision") VALUES (?, ?, ?, ?, ?, 'owner_command', ?, ?, ?)`).run(
      `drv_${n}`, at, P, revision, `run_${n}`, JSON.stringify(subject), JSON.stringify(verdicts), decision,
    );
  };
  const A = { kind: 'owner_build', target: 'android', build_ref: 'A' };
  const B = { kind: 'owner_build', target: 'android', build_ref: 'B' };
  const both = ['S2', 'S5'];
  const accepted = (screens = both, current = 'dsg_1') => humanTestEvidence(db, P, 'android', current, screens).accepted;
  confirmed(A, [v('S2', 'matches', 'device')]);
  assert.equal(accepted(), false, 'S5 unreviewed');
  assert.equal(accepted(['S2']), true, 'a target of one screen, matched');
  assert.equal(accepted([]), false, 'an empty screen set is never accepted');
  assert.equal(accepted(null), false, 'an unknown screen set is never accepted');
  assert.equal(accepted(both, null), false, 'no design version in force');
  confirmed(A, [v('S5', 'matches', 'simulation')]);
  assert.equal(accepted(), false, 'a simulation never counts');
  confirmed(A, [v('S5', 'not_observed', undefined, { not_observed_reason: 'not_reached' })]);
  assert.equal(accepted(), false, 'not_observed counts as unreviewed');
  confirmed(A, [v('S5', 'matches', 'device', { status: 'struck' })]);
  assert.equal(accepted(), false, 'a struck matches counts as unreviewed');
  confirmed(A, [v('S5', 'matches', 'device')], { decision: null });
  assert.equal(accepted(), false, 'a review not confirmed counts for nothing');
  confirmed(A, [v('S5', 'matches', 'emulator')], { revision: 'dsg_0' });
  assert.equal(accepted(), false, 'a verdict of another design version counts for nothing');
  confirmed(A, [v('S5', 'matches', 'emulator')]);
  assert.equal(accepted(), true, 'S2 and S5 match on build A, over two reviews of it');
  confirmed(A, [v('S5', 'deltas', 'device', { deltas: [{ owner_words: 'no quantity', kind: 'implementation' }] })]);
  assert.equal(accepted(), false, 'a later deltas on the same build revokes it');
  confirmed(A, [v('S5', 'matches', 'simulation')]);
  assert.equal(accepted(), false, 'a later simulation does not restore it');
  confirmed(A, [v('S5', 'matches', 'device')]);
  assert.equal(accepted(), true, 'a later counting matches restores it');
  confirmed({ kind: 'owner_build', target: 'web', build_ref: 'W' }, [{ ...v('S1', 'deltas', 'browser'), target: 'web' }]);
  assert.equal(accepted(), true, 'another target\'s review is not a review of this target');
  confirmed(B, [v('S5', 'matches', 'device')]);
  assert.equal(accepted(), false, 'S2 on A and S5 on the newer B never combine');
  confirmed(B, [v('S2', 'matches', 'device')]);
  assert.equal(accepted(), true, 'both on B');
  confirmed({ kind: 'owner_build', target: 'android', candidate: 'cnd_1' }, [v('S2', 'matches', 'device'), v('S5', 'matches', 'device', { status: 'struck' })]);
  assert.equal(accepted(), false, 'a newer build (a candidate) reviewed on S2 only: B\'s acceptance does not carry');
  confirmed({ kind: 'owner_build', target: 'android', candidate: 'cnd_1', build_ref: 'C' }, [v('S2', 'matches', 'device'), v('S5', 'matches', 'device')]);
  confirmed({ kind: 'owner_build', target: 'android', build_ref: 'C' }, [v('S5', 'deltas', 'device')]);
  assert.equal(accepted(), false, 'the build_ref names the build before the candidate');
  confirmed({}, [v('S2', 'matches', 'device'), v('S5', 'matches', 'device')]);
  assert.equal(accepted(), false, 'a review naming no build never accepts');
  const evidence = humanTestEvidence(db, P, 'android', 'dsg_1', both).evidence;
  assert.equal(evidence.some((e) => e.observed_on === 'device' && e.verdict === 'matches' && e.label === 'owner accepted'), true, 'every confirmed verdict kept as evidence');
  assert.equal(evidence.some((e) => e.design_revision === 'dsg_0'), true, 'an older design version\'s verdict kept as history');
});

test('N10, S7: observed_on with no evidence refused, naming it; owner evidence only from a device, emulator or simulator', async () => {
  const { bodyOf } = await import(join(dist, 'design', 'owner-review.js'));
  const file = { name: 'a.png', content_base64: Buffer.from('x').toString('base64') };
  assert.throws(() => bodyOf({ target: 'android', build_ref: 'b', observed_on: 'device' }), (err) => err.subject.field === 'observed_on' && /carries none/.test(err.reason));
  for (const o of ['device', 'emulator', 'simulator']) assert.equal(bodyOf({ target: 'android', build_ref: 'b', observed_on: o, evidence: [file] }).observed_on, o);
  for (const o of ['browser', 'simulation']) assert.throws(() => bodyOf({ target: 'android', build_ref: 'b', observed_on: o, evidence: [file] }), (err) => err.subject.field === 'observed_on');
  assert.equal(bodyOf({ target: 'android', build_ref: 'b', observed_on: 'device', evidence: [file] }).evidence[0].base64, file.content_base64, 'kept undecoded');
});
